import { describe, expect, it } from "vitest";
import { formatLength, formatMoney, formatVolume } from "./units.ts";

/**
 * Ожидаемые значения посчитаны вручную от 25.4 мм в дюйме, а не той же
 * формулой, что в коде: тест, пересчитывающий перевод тем же способом,
 * проходит по построению и не может разойтись с ошибкой.
 */

describe("длина в дюймах", () => {
  it("целый дюйм показывается без дроби", () => {
    expect(formatLength(25.4, "in")).toBe("1″");
    expect(formatLength(101.6, "in")).toBe("4″");
  });

  it("половина и четверть сокращаются, а не остаются шестнадцатыми", () => {
    // 12.7 мм = ровно 1/2″, 6.35 мм = 1/4″.
    expect(formatLength(12.7, "in")).toBe("1/2″");
    expect(formatLength(6.35, "in")).toBe("1/4″");
  });

  it("плашка 46 мм — это 1 13/16 дюйма", () => {
    // 46 ÷ 25.4 = 1.8110″; 0.8110 × 16 = 12.98 → 13/16.
    expect(formatLength(46, "in")).toBe("1 13/16″");
  });

  it("ноль не превращается в дробь", () => {
    expect(formatLength(0, "in")).toBe("0″");
  });

  it("миллиметры остаются целыми, где они целые", () => {
    expect(formatLength(46, "mm")).toBe("46");
    expect(formatLength(3.2, "mm")).toBe("3.2");
  });
});

describe("объём", () => {
  it("метрический показывается кубометрами", () => {
    expect(formatVolume(0.00864, "mm")).toBe("0.0086 м³");
  });

  it("дюймовый — в board feet", () => {
    // 1 BF = 12″ × 12″ × 1″ = 2360 см³. В 0.00864 м³ их 3.66.
    expect(formatVolume(0.00864, "in")).toBe("3.7 BF");
    expect(formatVolume(0.0023597372, "in")).toBe("1.0 BF");
  });
});

describe("деньги", () => {
  it("округляются до рубля и разделяются по разрядам", () => {
    // Разделитель разрядов сравнивается как «любой пробел»: локаль ставит
    // неразрывный, и прибивать тест к конкретному коду символа значит
    // ронять его при обновлении ICU, а не при поломке формата.
    expect(formatMoney(12345.67)).toMatch(/^12\s346\s₽$/u);
    expect(formatMoney(980.2)).toBe("980 ₽");
  });
});
