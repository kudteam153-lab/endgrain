/**
 * Модель узора — симулятор столярных операций (DECISIONS.md #D-01).
 *
 * Состояние проекта это стек операций, а не картинка. Отсюда главный
 * инвариант: неизготавливаемое состояние невыразимо. Раскрой, схема переклеек,
 * объём древесины и текст инструкции выводятся отсюда, а не пишутся рядом
 * вторым кодом, который со временем разойдётся с превью.
 */

/** Порода древесины. Палитра под РФ — FACTS.md #F-09. */
export interface Species {
  id: string
  name: string
  /** Цвет для SVG и 3D. Данные предметной области, не токен дизайн-системы. */
  color: string
  densityKgM3: number
  /** Цена за кубометр, ₽. */
  priceM3: number
}

/**
 * Ламель — заготовка, из которой начинается доска.
 *
 * `lengthMm` в #D-01 не было: там `Strip { speciesId, widthMm, thicknessMm }`.
 * Добавлено в день 1 — без длины не проверить, хватает ли заготовки
 * (FACTS.md #F-03), а это предупреждение дня 4. Отсутствие поля означало бы,
 * что модель выражает узор, но не выражает «столько дерева у меня нет».
 */
export interface Strip {
  speciesId: string
  widthMm: number
  thicknessMm: number
  lengthMm: number
}

/**
 * Направление волокна у заготовки относительно её лица.
 *
 * Определяет, как заготовки складываются в следующей склейке, и это не
 * условность модели, а физика верстака:
 *  - `long` — волокно вдоль длины. Ламели и ripped-полосы. Клеятся кромка
 *    к кромке, лицо растёт по X.
 *  - `end`  — торец. Плашки после поперечного реза, поставленные торцом вверх.
 *    Склеиваемые поверхности у них горизонтальные, лицо растёт по Y.
 */
export type Grain = 'long' | 'end'

/**
 * Рез.
 *
 * `kind` в #D-01 не было — там один `Cut { angleDeg, sliceWidthMm, kerfMm }`.
 * Разделено в день 1: продольный и поперечный рез дают геометрически разное.
 * Поперечный копирует лицо целиком и разворачивает волокно в торец;
 * продольный режет лицо на полосы и волокно не трогает. Без этого различия
 * трёхуровневый узор (плед) не выражается — см. LESSONS дня 1.
 */
export interface Cut {
  kind: 'rip' | 'crosscut'
  /** 90 — ортогональ. Иное — шеврон и ёлочка, день 5. */
  angleDeg: number
  sliceWidthMm: number
  /** Ширина пропила. Дефолт 3.2 — FACTS.md #F-01. */
  kerfMm: number
}

/** Операция над отдельной плашкой перед следующей склейкой. */
export type Transform =
  | { op: 'none' }
  /** Поворот на 180° в плоскости лица. */
  | { op: 'flip180' }
  /** Зеркало по горизонтали. */
  | { op: 'mirror' }
  /** Поворот на 90°: лицо меняет ширину с высотой. */
  | { op: 'rot90'; dir: 'cw' | 'ccw' }
  /**
   * Сдвиг на половину первой ламели — кирпичное смещение (FACTS.md #F-07).
   * Крайний элемент половинной ширины возникает сам: то, что уехало за край,
   * заходит с другой стороны. Он попадёт в кут-лист отдельной строкой.
   */
  | { op: 'halfWidth' }
  /** Циклический сдвиг на N целых ламелей: шахматка (1) и диагональ (i). */
  | { op: 'offset'; steps: number }

/**
 * Уровень: склейка → рез → трансформы.
 *
 * Первый уровень берёт сырьё, остальные — плашки предыдущего. Склеить можно
 * только то, что уже отрезано, поэтому источник это выбор из двух, а не
 * произвольный набор.
 */
export interface Level {
  source: { from: 'lumber'; strips: Strip[] } | { from: 'previous' }
  cut: Cut
  /**
   * Сколько плашек идёт в следующую склейку.
   *
   * Отдельно от `cut`: пила даёт столько, сколько выйдет из длины заготовки,
   * а в доску идёт нужное число. Расхождение между этими двумя величинами —
   * ровно то, из чего считается отход и предупреждение «не хватает длины».
   */
  pieceCount: number
  /** Трансформ на плашку по индексу. Короче `pieceCount` — повторяется циклом. */
  transforms: Transform[]
}

/** Проект целиком. Детерминирован: один `seed` — одна доска. */
export interface Project {
  species: Species[]
  levels: Level[]
  boardWMm: number
  boardLMm: number
  boardHMm: number
  units: 'mm' | 'in'
  seed: number
}

/** Прямоугольник лица: одна видимая ячейка узора. */
export interface Cell {
  xMm: number
  yMm: number
  wMm: number
  hMm: number
  speciesId: string
}

/** Лицо — торцевая поверхность, то, что видит глаз. */
export interface Face {
  wMm: number
  hMm: number
  cells: Cell[]
}

/** Заготовка на верстаке: лицо, длина вдоль волокна, направление волокна. */
export interface Piece {
  face: Face
  lengthMm: number
  grain: Grain
}
