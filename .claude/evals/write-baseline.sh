#!/usr/bin/env bash
# =============================================================================
# write-baseline.sh — записать эталон эвалов, КОГДА claude CLI доступен.
# Причина: baseline требует реальных вызовов модели (claude -p) по каждому кейсу.
# Без CLI раннер отказывается писать пустой эталон (иначе он спрячет регрессии).
# Этот скрипт: проверяет наличие claude в PATH, предупреждает о стоимости,
# запускает раннер из НЕЙТРАЛЬНОГО cwd и пишет baseline.
#
# Почему нейтральный cwd: claude -p наследует CLAUDE.md и хуки проекта, из
# которого запущен (LESSONS «Инструмент, спавнящий claude -p, наследует
# CLAUDE.md+хуки»). Запуск из временного каталога даёт вложенным сессиям
# чистое окружение.
#
# Почему протокол при этом СЕЕТСЯ обратно: изоляция нужна от хуков, а не от
# правил. Пока в песочницу не клали CLAUDE.md и .claude/rules/, эвалы измеряли
# базовую модель — и «страховка при правке CLAUDE.md» не могла поймать ни одной
# регрессии CLAUDE.md. Хуки, гейты и предохранители в песочницу по-прежнему не
# попадают.
#
# Почему кейсы пишут в ПОДКАТАЛОГИ cwd, а не в /tmp: на Windows это два разных
# места. Нативная сборка claude резолвит «/tmp/x» от корня диска (D:\tmp), а
# git-bash, которым раннер выполняет блок ```check```, понимает /tmp как D:\Temp
# — агент писал в один каталог, критерий смотрел в другой, и кейсы падали по
# среде, а не по поведению. Относительный путь одинаков для обоих. [D-433]
#
# Почему песочница получает свой settings.json: кейсы создают файлы, а
# headless-сессия не может запросить подтверждение записи — без гранта она
# отказывает и эталон получился бы «всё красное». Грант заперт в одноразовом
# каталоге и умирает вместе с ним.
#
# Использование:
#   bash .claude/evals/write-baseline.sh                        # запись эталона
#   bash .claude/evals/write-baseline.sh --check                # проверить готовность
#   bash .claude/evals/write-baseline.sh --case 05-grill-on-fork  # прицельный прогон
#     (аргументы уходят раннеру как есть; эталон при этом не переписывается)
# =============================================================================

set -uo pipefail

EVALS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER="$EVALS_DIR/run_evals.py"

. "$(dirname "${BASH_SOURCE[0]}")/../hooks/_lib.sh" 2>/dev/null || true
declare -f resolve_py >/dev/null 2>&1 && resolve_py || PY_BIN="python3"

CHECK_ONLY=0
[ "${1:-}" = "--check" ] && { CHECK_ONLY=1; shift; }

if command -v claude >/dev/null 2>&1; then
  echo "✅ claude найден: $(command -v claude)"
elif [ "$CHECK_ONLY" -eq 1 ]; then
  echo "⛔ claude CLI не в PATH — прогон невозможен, песочницу всё равно соберу ниже."
else
  echo "⛔ claude CLI не в PATH — baseline записать нельзя." >&2
  echo "   Раннер вызывает 'claude -p' по каждому кейсу; без CLI эталон был бы" >&2
  echo "   пустым прогоном и спрятал бы регрессии." >&2
  echo "" >&2
  echo "   Установить CLI и повторить:" >&2
  echo "     npm install -g @anthropic-ai/claude-code" >&2
  echo "     bash .claude/evals/write-baseline.sh" >&2
  exit 1
fi

if [ "$CHECK_ONLY" -eq 0 ]; then
  CASES=$(find "$EVALS_DIR/cases" -name '*.md' 2>/dev/null | wc -l | tr -d ' ')
  echo "⚠ Будет выполнено ${CASES} реальных прогонов 'claude -p' (модель вызывается"
  echo "  по-настоящему: время + токены). Запуск из нейтрального cwd, чтобы вложенные"
  echo "  сессии не подхватили хуки проекта."
  echo ""
fi

NEUTRAL="$(mktemp -d 2>/dev/null || echo "${TMPDIR:-/tmp}/evalrun_$$")"
mkdir -p "$NEUTRAL/.claude"
cat > "$NEUTRAL/.claude/settings.json" <<'JSON'
{
  "$comment": "Одноразовая песочница прогона эвалов. Кейсы создают файлы в подкаталогах этого каталога, а headless-сессия не может запросить подтверждение записи — без гранта эталон был бы «всё красное» по среде, а не по поведению. Каталог удаляется после прогона.",
  "permissions": {
    "defaultMode": "acceptEdits"
  }
}
JSON

# Протокол проекта — в песочницу. Без него эвалы меряют БАЗОВУЮ МОДЕЛЬ, а не
# обвязку: нейтральный cwd отсекает хуки (это и нужно), но вместе с ними уходят
# CLAUDE.md и .claude/rules/, то есть все правила, регрессию которых эвалы и
# заведены ловить. Кейс 05 падал именно на этом — требовал разметку «A)/B)» из
# конвенции §3, которую модели просто не показали, а остальные проходили лишь
# потому, что хирургичность и отказ от оверинжиниринга модель выдаёт и без
# инструкций. Копируются только правила: хуки, гейты и предохранители остаются
# за бортом, вложенная сессия по-прежнему изолирована.
# Побочный эффект принят: проектный CLAUDE.md может ссылаться на канон vault,
# которого в песочнице нет. Модель увидит недостающий путь — это шум в логе
# прогона, а не провал критерия.
PROJECT_ROOT="$(cd "$EVALS_DIR/../.." && pwd)"
SEEDED=""
if [ -f "$PROJECT_ROOT/CLAUDE.md" ]; then
  cp "$PROJECT_ROOT/CLAUDE.md" "$NEUTRAL/CLAUDE.md" && SEEDED="CLAUDE.md"
fi
if [ -d "$PROJECT_ROOT/.claude/rules" ]; then
  cp -r "$PROJECT_ROOT/.claude/rules" "$NEUTRAL/.claude/rules" \
    && SEEDED="${SEEDED:+$SEEDED + }.claude/rules/"
fi
if [ -n "$SEEDED" ]; then
  echo "✅ протокол проекта в песочнице: $SEEDED"
else
  echo "⚠ ни CLAUDE.md, ни .claude/rules/ не найдены в $PROJECT_ROOT —" >&2
  echo "  прогон измерит базовую модель, а не обвязку проекта." >&2
fi

if [ "$CHECK_ONLY" -eq 1 ]; then
  # Проверка без вызова модели: показать, с чем именно стартует вложенная сессия.
  # Смысл — увидеть глазами, что протокол доехал, а хуков в песочнице нет.
  echo ""
  echo "Состав песочницы ($NEUTRAL):"
  (cd "$NEUTRAL" && find . -maxdepth 3 -not -name '.' | sed 's|^\./|  |' | sort)
  rm -rf "$NEUTRAL" 2>/dev/null
  echo ""
  echo "Песочница удалена. Запись эталона — тот же вызов без --check."
  exit 0
fi

cd "$NEUTRAL" || { echo "не удалось перейти в нейтральный cwd" >&2; exit 1; }

# Без аргументов — запись эталона. С аргументами они уходят раннеру как есть:
# так делается прицельный прогон в той же песочнице («--case 05-grill-on-fork»),
# когда надо посмотреть на один кейс, не переписывая эталон.
if [ $# -gt 0 ]; then
  PYTHONUTF8=1 "$PY_BIN" "$RUNNER" "$@"
else
  PYTHONUTF8=1 "$PY_BIN" "$RUNNER" --baseline
fi
RC=$?

rm -rf "$NEUTRAL" 2>/dev/null
exit $RC
