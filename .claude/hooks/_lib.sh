#!/usr/bin/env bash
# =============================================================================
# _lib.sh — общие помощники хуков обвязки. Подключается через `source`.
# Не самостоятельный хук: не вешается на события, только предоставляет функции.
#
# Причина существования: резолвер python дублировался копипастой в 7 хуках.
# Урок «грепать весь набор» показал, что такой дубль легко пропустить при фиксе
# (класс бага прожил в 4 хуках после правки 3). Одно место правды — здесь.
#
# Надёжность: хуки подключают этот файл с деградацией (см. паттерн ниже), чтобы
# отсутствие/повреждение _lib.sh не роняло предохранитель, а давало fallback.
#   . "$(dirname "${BASH_SOURCE[0]}")/_lib.sh" 2>/dev/null || true
#   declare -f resolve_py >/dev/null 2>&1 && resolve_py || PY_BIN="python3"
# =============================================================================

# resolve_py — ставит переменную PY_BIN = имя рабочего python.
# Пропускает execution-alias из WindowsApps: на Windows `python3` часто резолвится
# в сломанную 0-байтную заглушку, из-за которой разбор JSON в подпроцессе хука
# молча даёт пустой результат → хук делает exit 0 → выглядит включённым, но не
# исполняется (для guard-* это снятый предохранитель). Fallback — python3.
# Всегда возвращает 0, чтобы не сбивать `&& resolve_py` в вызывающем коде.
resolve_py() {
  PY_BIN=""
  local _c _p
  for _c in python3 python py; do
    _p="$(command -v "$_c" 2>/dev/null)" || continue
    case "$_p" in *WindowsApps*) continue ;; esac
    PY_BIN="$_c"; break
  done
  [ -z "$PY_BIN" ] && PY_BIN="python3"
  return 0
}

# stop_context — отдаёт напоминание Stop-гейта через additionalContext.
#
# Раньше гейты писали в stderr и выходили с 2. Код 2 на Stop заставляет модель
# сделать лишний оборот только чтобы прочитать напоминание, которое ничего не
# блокирует. additionalContext кладёт тот же текст без оборота.
#
# Возврат: 0 — текст отдан; 1 — python недоступен, текст ушёл в stderr и
# вызывающий должен сам решить, падать ли с 2 (прежнее поведение).
stop_context() {  # stop_context <текст> [событие]
  local text="$1" event="${2:-Stop}"
  declare -f resolve_py >/dev/null 2>&1 && resolve_py
  [ -n "${PY_BIN:-}" ] || PY_BIN="python3"

  CTX_TEXT="$text" CTX_EVENT="$event" PYTHONUTF8=1 "$PY_BIN" -c '
import json, os, sys
sys.stdout.write(json.dumps({
    "hookSpecificOutput": {
        "hookEventName": os.environ["CTX_EVENT"],
        "additionalContext": os.environ["CTX_TEXT"],
    }
}, ensure_ascii=False))
' 2>/dev/null && return 0

  printf '%s\n' "$text" >&2
  return 1
}

# canon_block — печатает, где у проекта лежит канон и что ещё нужно знать
# исполнителю. Пусто, если сообщать нечего.
#
# Зачем: скиллы, команды и субагенты ссылаются на `DECISIONS.md`,
# `CORE_PRINCIPLES.md` голыми именами — так они остаются переносимыми между
# проектами. В vault-топологии канон лежит в СОСЕДНЕМ репозитории, и голое имя
# там не резолвится: `grill` с его 34 вызовами клал бы черновик решения в никуда.
#
# Правим не компоненты (иначе каждый новый пришлось бы адаптировать в каждом
# проекте — тот же дрейф, что развёл session-log.sh на три версии), а сообщаем
# раскладку на старте. Источники два:
#   1. DOCS_ROOT из "env" в .claude/settings.json проекта — где канон;
#   2. .claude/project-context.md — всё остальное, что знает только проект
#      (свои разделы канона, проектные скиллы, файлы вне DOCS_ROOT).
# Оба местные, синхронизации не подлежат.
canon_block() {
  local root="${DOCS_ROOT:-}" dir="${CLAUDE_PROJECT_DIR:-.}" out="" extra=""

  if [ -n "$root" ] && [ "$root" != "." ]; then
    if [ -d "$dir/$root" ] || [ -d "$root" ]; then
      # Абсолютный путь, а не только относительный: 27.07 в обкатке субагенты
      # получали «../detailbase-vault/…», не знали точки отсчёта и промахивались
      # по два раза, прежде чем попасть (D:\ai-memory\wiki\…, d:\detailbase-vault\…).
      # pwd -W даёт виндовую форму, которую понимают инструменты чтения.
      local abs
      abs="$(cd "$dir/$root" 2>/dev/null && { pwd -W 2>/dev/null || pwd; })"
      out="Канон-документы проекта лежат НЕ в корне, а в: ${abs:-$root}
(относительно корня проекта это ${root}/)
Скиллы, команды и субагенты ссылаются на них голыми именами (\`DECISIONS.md\`, \`CORE_PRINCIPLES.md\`, \`NAVIGATION.md\`) — читай и пиши их по АБСОЛЮТНОМУ пути выше, не подставляя своё представление о корне.
В корне репозитория этих файлов нет: не заводи их заново, если не нашёл."
    else
      # Молчать здесь нельзя: компоненты пойдут писать канон в корень, и
      # расхождение обнаружится через недели.
      out="DOCS_ROOT задан как «${root}», но такого каталога нет — проверь .claude/settings.json, ссылки на канон работать не будут."
    fi
  fi

  if [ -f "$dir/.claude/project-context.md" ]; then
    extra="$(cat "$dir/.claude/project-context.md" 2>/dev/null)"
    if [ -n "$extra" ]; then
      out="${out:+$out
}$extra"
    fi
  fi

  printf '%s' "$out"
}
